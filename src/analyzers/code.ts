function extractCommentText(trimmedLine: string, profile: CodeLanguageProfile): string | null {
  if (trimmedLine.startsWith(profile.lineComment)) {
    return trimmedLine.slice(profile.lineComment.length).trim()
  }
  if (profile.altLineComment.length > 0 && trimmedLine.startsWith(profile.altLineComment)) {
    return trimmedLine.slice(profile.altLineComment.length).trim()
  }
  if (profile.supportsBlockComment && (trimmedLine.startsWith('/*') || trimmedLine.startsWith('*'))) {
    let s = trimmedLine
    if (s.startsWith('/**')) s = s.slice(3)
    else if (s.startsWith('/*')) s = s.slice(2)
    else if (s.startsWith('*')) s = s.slice(1)
    if (s.endsWith('*/')) s = s.slice(0, s.length - 2)
    return s.trim()
  }
  return null
}

function isStepComment(commentLower: string): boolean {
  if (/^step\s+\d+[:.)\-\s]/.test(commentLower)) return true
  if (/^adım\s+\d+[:.)\-\s]/.test(commentLower)) return true
  if (/^\d+\.\s+[a-zçğıöşü]/.test(commentLower)) return true
  return false
}

export function analyzeCode(buf: Uint8Array, format: string): AnalyzerResult {
  const findings: ForensicFinding[] = []
  const metadata: KeyValueEntry[] = []
  const metrics: KeyValueEntry[] = []
  const generatorHints: string[] = []

  const profile = getLanguageProfile(format)
  const text = Buffer.from(buf).toString('utf8')
  const lowerAll = text.toLowerCase()
  const lines = text.split(/\r?\n/)

  metadata.push({ key: 'code_language', value: profile.name })
  metadata.push({ key: 'text_encoding', value: 'UTF-8' })

  let totalLines = lines.length
  let nonEmptyLines = 0
  let codeLines = 0
  let commentLines = 0
  let docBlockCount = 0
  let inBlockComment = false
  let inTripleDoc = false
  let narrationHits = 0
  let stepCommentCount = 0
  let emDashInComments = 0
  let emojiInComments = 0
  let trailingWsLines = 0
  let pragmaticHumanHits = 0
  let ticketRefHits = 0
  let codeLineLenSum = 0
  let codeLineLenSq = 0

  const matchedNarration: string[] = []
  const matchedOmissions: string[] = []
  const matchedPlaceholders: string[] = []
  const matchedExplicitIds = new Set<string>()
  const matchedHumanEvidence: string[] = []

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i]!
    if (rawLine.length > 0 && (rawLine.endsWith(' ') || rawLine.endsWith('\t'))) {
      trailingWsLines++
    }
    const trimmed = rawLine.trim()
    if (trimmed.length === 0) continue
    nonEmptyLines++

    // Track multi-line docstrings / block comments
    let isCommentLine = false
    let commentBody = ''

    if (profile.supportsTripleQuoteDoc) {
      if (trimmed.startsWith('"""') || trimmed.startsWith("'''")) {
        const delim = trimmed.slice(0, 3)
        isCommentLine = true
        commentBody = trimmed.slice(3)
        if (!inTripleDoc) {
          docBlockCount++
          if (trimmed.length === 3 || !trimmed.slice(3).endsWith(delim)) {
            inTripleDoc = true
          }
        } else {
          inTripleDoc = false
        }
      } else if (inTripleDoc) {
        isCommentLine = true
        commentBody = trimmed
      }
    }

    if (!isCommentLine && profile.supportsBlockComment) {
      if (inBlockComment) {
        isCommentLine = true
        commentBody = trimmed.replace(/^\*\s?/, '').replace(/\*\/$/, '').trim()
        if (trimmed.indexOf('*/') >= 0) inBlockComment = false
      } else if (trimmed.startsWith('/*')) {
        isCommentLine = true
        if (trimmed.startsWith('/**')) docBlockCount++
        commentBody = extractCommentText(trimmed, profile) ?? ''
        if (trimmed.indexOf('*/') < 0) inBlockComment = true
      }
    }

    if (!isCommentLine) {
      const single = extractCommentText(trimmed, profile)
      if (single !== null) {
        isCommentLine = true
        commentBody = single
        if (profile.name === 'RUST' && trimmed.startsWith('///')) docBlockCount++
      }
    }

    if (isCommentLine) {
      commentLines++
      const cLower = commentBody.toLowerCase()

      if (commentBody.indexOf('—') >= 0) emDashInComments++
      if (/[✅🚀⚡🔥💡✨🎯📌]/.test(commentBody)) emojiInComments++

      if (isStepComment(cLower)) {
        stepCommentCount++
      }

      for (let p = 0; p < NARRATION_COMMENT_PREFIXES.length; p++) {
        const prefix = NARRATION_COMMENT_PREFIXES[p]!
        if (cLower.startsWith(prefix) || cLower.indexOf(` ${prefix}`) >= 0) {
          narrationHits++
          if (matchedNarration.length < 6) {
            addUnique(matchedNarration, commentBody.slice(0, 64))
          }
          break
        }
      }

      for (let o = 0; o < OMISSION_COMMENT_PATTERNS.length; o++) {
        if (cLower.indexOf(OMISSION_COMMENT_PATTERNS[o]!) >= 0) {
          addUnique(matchedOmissions, commentBody.slice(0, 72))
        }
      }

      for (let h = 0; h < PRAGMATIC_HUMAN_MARKERS.length; h++) {
        const hm = PRAGMATIC_HUMAN_MARKERS[h]!
        if (cLower.indexOf(hm) >= 0) {
          pragmaticHumanHits++
          if (matchedHumanEvidence.length < 5) addUnique(matchedHumanEvidence, hm.trim())
        }
      }

      if (/(?:todo\([a-z0-9_-]+\)|#[1-9]\d{1,5}\b|[A-Z]{2,6}-\d{2,5}\b)/.test(commentBody)) {
        ticketRefHits++
        if (matchedHumanEvidence.length < 5) addUnique(matchedHumanEvidence, 'ticket/issue ref')
      }
    } else {
      codeLines++
      codeLineLenSum += trimmed.length
      codeLineLenSq += trimmed.length * trimmed.length
      // Also check inline pragmatic markers like `// eslint-disable` or `#[allow(...)]`
      const lLower = trimmed.toLowerCase()
      for (let h = 0; h < PRAGMATIC_HUMAN_MARKERS.length; h++) {
        const hm = PRAGMATIC_HUMAN_MARKERS[h]!
        if (lLower.indexOf(hm) >= 0) {
          pragmaticHumanHits++
          if (matchedHumanEvidence.length < 5) addUnique(matchedHumanEvidence, hm.trim())
        }
      }
    }
  }

  // Check explicit AI attribution headers/comments
  for (let m = 0; m < EXPLICIT_CODE_AI_MARKERS.length; m++) {
    const rule = EXPLICIT_CODE_AI_MARKERS[m]!
    if (matchedExplicitIds.has(rule.id)) continue
    const idx = lowerAll.indexOf(rule.pattern)
    if (idx < 0) continue
    matchedExplicitIds.add(rule.id)
    addUnique(generatorHints, rule.generator)
    const snippet = text.slice(Math.max(0, idx - 16), Math.min(text.length, idx + rule.pattern.length + 40)).replace(/\s+/g, ' ').trim()
    findings.push({
      id: `sig_${rule.id}`,
      category: 'provenance',
      severity: 'critical',
      scoreDelta: 65,
      titleTr: `Açık AI kod üretim imzası bulundu: ${rule.generator}`,
      titleEn: `Explicit AI code attribution found: ${rule.generator}`,
      detailTr: `Kaynak kod yorum veya başlığında doğrudan '${rule.pattern}' üretim beyanı yer alıyor.`,
      detailEn: `Source code comment or header explicitly declares '${rule.pattern}'.`,
      evidence: snippet
    })
  }

  // Check tutorial/placeholder boilerplate patterns
  for (let p = 0; p < PLACEHOLDER_PATTERNS.length; p++) {
    const pat = PLACEHOLDER_PATTERNS[p]!
    if (lowerAll.indexOf(pat) >= 0) {
      addUnique(matchedPlaceholders, pat)
    }
  }

  // Detect AI-loop / autonomous LLM feedback loop patterns in source code
  const matchedLlmApis: string[] = []
  for (let i = 0; i < LLM_API_SIGNALS.length; i++) {
    const sig = LLM_API_SIGNALS[i]!
    if (lowerAll.indexOf(sig) >= 0) addUnique(matchedLlmApis, sig)
  }

  const matchedLoops: string[] = []
  for (let i = 0; i < LOOP_CONSTRUCT_SIGNALS.length; i++) {
    const sig = LOOP_CONSTRUCT_SIGNALS[i]!
    if (lowerAll.indexOf(sig) >= 0) addUnique(matchedLoops, sig)
  }

  let hasLoopGuard = false
  for (let i = 0; i < LOOP_GUARD_SIGNALS.length; i++) {
    if (lowerAll.indexOf(LOOP_GUARD_SIGNALS[i]!) >= 0) {
      hasLoopGuard = true
      break
    }
  }

  const matchedSelfFeedback: string[] = []
  for (let i = 0; i < SELF_FEEDBACK_LOOP_SIGNALS.length; i++) {
    const sig = SELF_FEEDBACK_LOOP_SIGNALS[i]!
    if (lowerAll.indexOf(sig) >= 0) addUnique(matchedSelfFeedback, sig)
  }

  let stubCount = 0
  for (let i = 0; i < STUB_PLACEHOLDER_PATTERNS.length; i++) {
    const pat = STUB_PLACEHOLDER_PATTERNS[i]!
    let idx = lowerAll.indexOf(pat)
    while (idx >= 0) {
      stubCount++
      idx = lowerAll.indexOf(pat, idx + pat.length)
    }
  }

  // Count textbook JSDoc/docstring tags (@param/@returns or Args:/Returns:)
  const paramMatches = text.match(/@param\b|\bArgs:\s*$|^\s*Returns:\s*$/gm)
  const docTagCount = paramMatches ? paramMatches.length : 0

  const commentRatio = nonEmptyLines > 0 ? commentLines / nonEmptyLines : 0
  const narrationPer100Code = codeLines > 0 ? (narrationHits / codeLines) * 100 : 0
  const avgCodeLineLen = codeLines > 0 ? codeLineLenSum / codeLines : 0
  const codeLineLenCv =
    codeLines > 2 && avgCodeLineLen > 0
      ? Math.sqrt(Math.max(0, codeLineLenSq / codeLines - avgCodeLineLen * avgCodeLineLen)) / avgCodeLineLen
      : 0

  metrics.push({ key: 'code_total_lines', value: String(totalLines) })
  metrics.push({ key: 'code_lines', value: String(codeLines) })
  metrics.push({ key: 'code_comment_lines', value: String(commentLines) })
  metrics.push({ key: 'code_comment_ratio', value: `${round2(commentRatio * 100)}%` })
  metrics.push({ key: 'code_narration_hits', value: String(narrationHits) })
  metrics.push({ key: 'code_step_comments', value: String(stepCommentCount) })
  metrics.push({ key: 'code_omission_comments', value: String(matchedOmissions.length) })
  metrics.push({ key: 'code_doc_blocks', value: String(docBlockCount) })
  metrics.push({ key: 'code_doc_tags', value: String(docTagCount) })
  metrics.push({ key: 'code_comment_emdash_emoji', value: String(emDashInComments + emojiInComments) })
  metrics.push({ key: 'code_line_len_cv', value: String(round2(codeLineLenCv)) })
  metrics.push({ key: 'code_pragmatic_human_markers', value: String(pragmaticHumanHits + ticketRefHits) })
  metrics.push({ key: 'code_llm_api_signals', value: String(matchedLlmApis.length) })
  metrics.push({ key: 'code_self_feedback_signals', value: String(matchedSelfFeedback.length) })
  metrics.push({ key: 'code_stub_placeholders', value: String(stubCount) })

  if (matchedLlmApis.length > 0 && matchedLoops.length > 0) {
    const unbounded = !hasLoopGuard
    findings.push({
      id: unbounded ? 'code_unbounded_llm_loop' : 'code_autonomous_llm_loop',
      category: 'ailoop',
      severity: unbounded ? 'high' : 'medium',
      scoreDelta: unbounded ? 32 : 18,
      titleTr: unbounded
        ? 'Sınırsız otonom LLM döngüsü tespit edildi (AI-Loop)'
        : 'Otonom LLM ajan döngüsü tespit edildi (AI-Loop)',
      titleEn: unbounded
        ? 'Unbounded autonomous LLM loop detected (AI-Loop)'
        : 'Autonomous LLM agent loop detected (AI-Loop)',
      detailTr: unbounded
        ? 'Kaynak kodda max_iterations/budget/onay koruması olmadan sonsuz döngü içinde LLM API çağrısı yapılıyor.'
        : 'Kaynak kodda döngü içinde yinelenen LLM API çağrısı bulunuyor.',
      detailEn: unbounded
        ? 'Code invokes LLM APIs inside an unbounded loop without max-iteration, budget, or human-approval guards.'
        : 'Code executes repeated LLM API calls inside an orchestration loop.',
      evidence: `apis=[${matchedLlmApis.slice(0, 3).join(', ')}] loops=[${matchedLoops.slice(0, 2).join(', ')}] guard=${hasLoopGuard ? 'yes' : 'no'}`
    })
  }

  if (matchedSelfFeedback.length >= 1) {
    const score = matchedSelfFeedback.length >= 2 ? 26 : 16
    findings.push({
      id: 'code_self_prompt_feedback_loop',
      category: 'ailoop',
      severity: matchedSelfFeedback.length >= 2 ? 'high' : 'medium',
      scoreDelta: score,
      titleTr: `Kendi kendini besleyen AI geri besleme döngüsü örüntüsü (${matchedSelfFeedback.length})`,
      titleEn: `Self-feeding AI feedback loop pattern (${matchedSelfFeedback.length})`,
      detailTr: 'Model çıktısını doğrudan tekrar modele besleyen otonom döngü/öz-düzeltme (ralph/self-critique/auto-fix loop) yapısı bulundu.',
      detailEn: 'Contains self-feeding prompt/refinement loop patterns feeding model outputs directly back into subsequent LLM turns.',
      evidence: matchedSelfFeedback.slice(0, 5).join(', ')
    })
  }

  if (stubCount >= 2 && (narrationHits >= 2 || matchedOmissions.length > 0)) {
    findings.push({
      id: 'code_stub_proliferation',
      category: 'ailoop',
      severity: 'medium',
      scoreDelta: 14,
      titleTr: `Tamamlanmamış AI taslak/stub yığılması (${stubCount} adet)`,
      titleEn: `Incomplete AI stub/placeholder proliferation (${stubCount} hits)`,
      detailTr: 'Kodda anlatım yorumlarıyla birlikte birden fazla uygulanmamış taslak (NotImplemented / TODO implement) blok yer alıyor.',
      detailEn: 'Multiple unimplemented stubs paired with AI narration or omission comments.',
      evidence: `stubs=${stubCount}`
    })
  }

  // Forensic Scoring Rules for Source Code
  if (matchedOmissions.length > 0) {
    findings.push({
      id: 'code_llm_omission_comment',
      category: 'stylometry',
      severity: 'high',
      scoreDelta: 34,
      titleTr: `LLM kısaltma/atlama yorumu tespit edildi (${matchedOmissions.length})`,
      titleEn: `LLM code-omission placeholder comment detected (${matchedOmissions.length})`,
      detailTr: 'Kod içinde yapay zeka sohbet/editör çıktılarından kopyalanan "... existing code / rest of implementation" tipi atlama yorumu bulunuyor.',
      detailEn: 'Code contains LLM-style omission comments (e.g. "... existing code" / "rest of implementation").',
      evidence: matchedOmissions.join('; ')
    })
  }

  if (stepCommentCount >= 3) {
    findings.push({
      id: 'code_numbered_step_narration',
      category: 'stylometry',
      severity: 'high',
      scoreDelta: 22,
      titleTr: `Numaralı adım anlatım yorumları (${stepCommentCount} adım)`,
      titleEn: `Numbered step-by-step narration comments (${stepCommentCount} steps)`,
      detailTr: 'Kod satırları "Step 1 / 1. ..." biçiminde ders kitabı/LLM tarzı sıralı adım yorumlarıyla anlatılmış.',
      detailEn: 'Sequential "Step 1 / 1. ..." tutorial-style narration comments typical of LLM code generation.',
      evidence: `stepComments=${stepCommentCount}`
    })
  }

  if (narrationHits >= 4 && narrationPer100Code >= 8) {
    const delta = Math.min(28, 14 + narrationHits * 2)
    findings.push({
      id: 'code_high_narration_density',
      category: 'stylometry',
      severity: 'high',
      scoreDelta: delta,
      titleTr: `Yüksek satır-satır LLM anlatım yorumu yoğunluğu (${narrationHits} yorum)`,
      titleEn: `High play-by-play LLM narration comment density (${narrationHits} hits)`,
      detailTr: 'Açık kod akışını tekrarlayan "Initialize / Validate / Check if / Return the" kalıbında yoğun anlatım yorumları mevcut.',
      detailEn: 'Dense obvious-action narration comments ("Initialize / Validate / Check if / Return the") characteristic of LLM output.',
      evidence: matchedNarration.slice(0, 4).join(' | ')
    })
  } else if (narrationHits >= 2 && commentRatio >= 0.25) {
    findings.push({
      id: 'code_moderate_narration_comments',
      category: 'stylometry',
      severity: 'medium',
      scoreDelta: 12,
      titleTr: `Yüksek yorum oranı ve anlatım kalıpları (%${round2(commentRatio * 100)})`,
      titleEn: `Elevated comment ratio with narration phrasing (${round2(commentRatio * 100)}%)`,
      detailTr: 'Kodun önemli bir bölümü açıklayıcı anlatım yorumlarından oluşuyor.',
      detailEn: 'Unusually high fraction of lines are explanatory narration comments.',
      evidence: `commentRatio=${round2(commentRatio * 100)}%, hits=${narrationHits}`
    })
  }

  if (emDashInComments + emojiInComments >= 2) {
    findings.push({
      id: 'code_llm_comment_typography',
      category: 'stylometry',
      severity: 'medium',
      scoreDelta: 14,
      titleTr: `Kod yorumlarında LLM tipografisi / emoji kullanımı (${emDashInComments} uzun tire, ${emojiInComments} emoji)`,
      titleEn: `LLM typography / emoji markers in code comments (${emDashInComments} em-dashes, ${emojiInComments} emojis)`,
      detailTr: 'Kaynak kod yorumlarında uzun tire (—) veya dekoratif emojiler yoğun kullanılmış; sohbet tabanlı LLM çıktılarında sık görülür.',
      detailEn: 'Frequent em-dashes (—) or decorative emojis inside code comments, a common artifact of chat-generated code.',
      evidence: `emDash=${emDashInComments}, emoji=${emojiInComments}`
    })
  }

  if (matchedPlaceholders.length >= 1 && (narrationHits >= 2 || stepCommentCount >= 2)) {
    findings.push({
      id: 'code_tutorial_placeholders',
      category: 'stylometry',
      severity: 'medium',
      scoreDelta: 12,
      titleTr: `Şablon / yer tutucu (placeholder) değerler (${matchedPlaceholders.length})`,
      titleEn: `Template / placeholder demo values (${matchedPlaceholders.length})`,
      detailTr: 'Anlatım yorumlarıyla birlikte örnek/yer tutucu değerler (ör. YOUR_API_KEY, example.com) bulundu.',
      detailEn: 'Demo/placeholder values (e.g. YOUR_API_KEY, example.com) paired with explanatory comments.',
      evidence: matchedPlaceholders.join(', ')
    })
  }

  if (docBlockCount >= 2 && docTagCount >= 4 && codeLines > 0 && codeLines <= 120 && narrationHits >= 2) {
    findings.push({
      id: 'code_excessive_textbook_docblocks',
      category: 'stylometry',
      severity: 'low',
      scoreDelta: 10,
      titleTr: `Kısa kodda yoğun şablon dokümantasyon bloğu (${docBlockCount} blok, ${docTagCount} etiket)`,
      titleEn: `Dense textbook docblocks in short file (${docBlockCount} blocks, ${docTagCount} tags)`,
      detailTr: 'Kısa yardımcı fonksiyonların tamamı tekdüze @param/@returns veya Args/Returns şablonlarıyla belgelenmiş.',
      detailEn: 'Uniform textbook docblocks covering every small helper in a short file.',
      evidence: `docBlocks=${docBlockCount}, docTags=${docTagCount}, codeLines=${codeLines}`
    })
  }

  // Authentic engineering signals (negative weight to protect real human codebases)
  if (pragmaticHumanHits + ticketRefHits >= 2 && matchedOmissions.length === 0 && stepCommentCount === 0) {
    findings.push({
      id: 'code_pragmatic_engineering_markers',
      category: 'stylometry',
      severity: 'authentic',
      scoreDelta: -16,
      titleTr: 'Pragmatik insan mühendisliği izleri (FIXME / linter baskılama / ticket referansı)',
      titleEn: 'Pragmatic human engineering markers (FIXME / lint suppressions / issue refs)',
      detailTr: 'Gerçek bakım geçmişine özgü ticket referansları, FIXME veya derleyici/linter istisnaları bulundu.',
      detailEn: 'Contains maintenance-history markers such as issue/ticket refs, FIXME notes, or targeted lint suppressions.',
      evidence: matchedHumanEvidence.join(', ')
    })
  }

  if (
    codeLines >= 15 &&
    narrationHits === 0 &&
    stepCommentCount === 0 &&
    matchedOmissions.length === 0 &&
    emDashInComments === 0 &&
    commentRatio < 0.12
  ) {
    findings.push({
      id: 'code_concise_organic_style',
      category: 'stylometry',
      severity: 'authentic',
      scoreDelta: -14,
      titleTr: 'Sade, anlatımsız doğal kod stili',
      titleEn: 'Concise organic code style without LLM narration',
      detailTr: 'Aşırı anlatım yorumu, adım numaralandırması veya LLM şablon izi gözlemlenmedi.',
      detailEn: 'No play-by-play narration comments, numbered steps, or LLM template artifacts detected.',
      evidence: `codeLines=${codeLines}, commentRatio=${round2(commentRatio * 100)}%, narration=0`
    })
  }

  return {
    mediaCategory: 'code',
    detectedFormat: format,
    findings,
    metadata,
    metrics,
    generatorHints
  }
}
