interface CodeLanguageProfile {
  name: string
  lineComment: string
  altLineComment: string
  supportsBlockComment: boolean
  supportsTripleQuoteDoc: boolean
}

function getLanguageProfile(format: string): CodeLanguageProfile {
  if (format === 'PYTHON' || format === 'MOJO' || format === 'RUBY' || format === 'ELIXIR' || format === 'SHELL') {
    return {
      name: format,
      lineComment: '#',
      altLineComment: '',
      supportsBlockComment: false,
      supportsTripleQuoteDoc: format === 'PYTHON' || format === 'MOJO'
    }
  }
  if (format === 'SQL') {
    return {
      name: format,
      lineComment: '--',
      altLineComment: '',
      supportsBlockComment: true,
      supportsTripleQuoteDoc: false
    }
  }
  if (format === 'PHP') {
    return {
      name: format,
      lineComment: '//',
      altLineComment: '#',
      supportsBlockComment: true,
      supportsTripleQuoteDoc: false
    }
  }
  // JS, TS, JSX, TSX, Rust, Go, Swift, Kotlin, Java, C#, C, C++, Zig, Gleam, Dart, Scala
  return {
    name: format,
    lineComment: '//',
    altLineComment: '',
    supportsBlockComment: true,
    supportsTripleQuoteDoc: false
  }
}

